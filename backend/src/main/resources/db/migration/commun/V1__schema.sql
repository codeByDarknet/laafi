-- Schéma Laafi (compatible PostgreSQL et H2 en mode PostgreSQL pour les tests).
-- AUCUNE table ne stocke de contenu de message : uniquement des métadonnées administratives.

-- Journal probant des accusés de lecture (chaîné + signé, voir JournalProbant.java)
CREATE TABLE accuse_lecture (
    id             BIGINT       NOT NULL PRIMARY KEY,
    room_id        VARCHAR(255) NOT NULL,
    event_id       VARCHAR(255) NOT NULL,
    agent          VARCHAR(255) NOT NULL,
    empreinte      VARCHAR(64)  NOT NULL,
    horodatage     TIMESTAMP WITH TIME ZONE NOT NULL,
    hash_precedent VARCHAR(64)  NOT NULL,
    hash_entree    VARCHAR(64)  NOT NULL,
    signature      VARCHAR(128) NOT NULL,
    CONSTRAINT uq_accuse_event_agent UNIQUE (event_id, agent),
    -- Une entrée ne peut avoir qu'un seul successeur : la chaîne ne peut pas « bifurquer ».
    CONSTRAINT uq_accuse_hash_precedent UNIQUE (hash_precedent),
    CONSTRAINT uq_accuse_hash_entree UNIQUE (hash_entree)
);
CREATE INDEX idx_accuse_event ON accuse_lecture (event_id);

-- Journal d'audit administratif (acteur, action, cible, horodatage, motif) — jamais de contenu
CREATE TABLE evenement_audit (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    horodatage TIMESTAMP WITH TIME ZONE NOT NULL,
    acteur     VARCHAR(255) NOT NULL,
    action     VARCHAR(64)  NOT NULL,
    cible      VARCHAR(255),
    ministere  VARCHAR(32),
    motif      VARCHAR(1000)
);
CREATE INDEX idx_audit_ministere ON evenement_audit (ministere);

-- Statut administratif complémentaire à Keycloak (APPAREILS_REVOQUES)
CREATE TABLE etat_agent (
    username   VARCHAR(255) NOT NULL PRIMARY KEY,
    statut     VARCHAR(32)  NOT NULL,
    modifie_le TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Politiques de classification (contrat §6)
CREATE TABLE politique_classification (
    niveau              VARCHAR(32)  NOT NULL PRIMARY KEY,
    libelle             VARCHAR(255) NOT NULL,
    transfert           VARCHAR(32)  NOT NULL,
    copie               BOOLEAN      NOT NULL,
    expiration_jours    INTEGER,
    filigrane           BOOLEAN      NOT NULL,
    filigrane_nominatif BOOLEAN      NOT NULL,
    flou_hors_focus     BOOLEAN      NOT NULL,
    modifie_par         VARCHAR(255),
    modifie_le          TIMESTAMP WITH TIME ZONE
);

-- Registre des canaux institutionnels (métadonnées seulement ; le salon Matrix est créé par le client)
CREATE TABLE canal_institutionnel (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id        VARCHAR(255)  NOT NULL UNIQUE,
    nom            VARCHAR(255)  NOT NULL,
    ministere      VARCHAR(32)   NOT NULL,
    description    VARCHAR(1000),
    classification VARCHAR(32)   NOT NULL,
    cree_par       VARCHAR(255)  NOT NULL,
    cree_le        TIMESTAMP WITH TIME ZONE NOT NULL
);
